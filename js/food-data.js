/* Целевые КБЖУ. Считаны так, чтобы Б×4 + Ж×9 + У×4 совпадало с калоражем,
   а доля жира была реальной для рациона на бёдрах, яйцах и сыре. */
function nutritionTarget(){
  const info=weekInfo();
  let t;
  if(isSession())          t={k:2850,p:160,f:90,c:350};   /* сессия: поддержание, голове нужны углеводы */
  else if(state.cycle===1) t={k:2600,p:165,f:78,c:310};   /* цикл 1 = сушка до ~12 %: −0,3…0,6 кг/нед */
  else if(state.cycle===2){
    /* после сушки калории поднимаются ступенями, а не прыжком на +575 */
    t = state.week===1 ? {k:2950,p:158,f:110,c:332}
      : state.week===2 ? {k:3075,p:158,f:110,c:363}
      :                  {k:3175,p:158,f:110,c:388};
  }
  else {
    const x=cycle3(Math.min(state.week,24));
    t = (x.kind==='hyper') ? {k:3400,p:170,f:115,c:421} : {k:3200,p:170,f:108,c:387};
  }
  /* поправка по замерам (вкладка «Прогресс»): ±150 ккал за счёт углеводов */
  const adj = isSession() ? 0 : ((settings.kcalAdj||{})[state.cycle]||0);
  if(adj) t={k:t.k+adj, p:t.p, f:t.f, c:t.c+Math.round(adj/4)};

  /* разгрузка: минус 150 ккал, срезаем углеводами, белок не трогаем */
  if(info.kind==='deload') t={k:t.k-150, p:t.p, f:t.f, c:t.c-38};

  /* Пропущенные сессии: силовая стоит примерно 300 ккал, кардио 250.
     Размазываем по семи дням — поэтому поправка намеренно небольшая.
     В цикле 1 цель — сушка с сохранением силы, в циклах 2–3 — набор. */
  const m=missedSessions();
  if(m.total){
    const cut=Math.round((m.gym*300 + m.run*250)/7);
    t={k:t.k-cut, p:t.p, f:t.f, c:t.c-Math.round(cut/4)};
  }
  return t;
}
const portionFactor = () => nutritionTarget().k / 2850;
