/* Цикл 3: 24 недели, блоки по 6. Чётный блок — гипертрофия,
   нечётный — реконверсия. Шестая неделя блока разгрузочная. */
/* После 24-й недели план пройден: повторяется последний блок (недели 19–24).
   Номера недель идут дальше (25, 26…), чтобы записи первого прохода не перезаписывались */
const c3w = w => w<=24 ? w : 19 + (w-25)%6;
function cycle3(week){
  const base={sq:105,tr:125,oh:52.5};
  const m=c3w(week), blk=Math.floor((m-1)/6), wIn=((m-1)%6)+1;
  /* июль–август — каникулы, главный блок года: сила и мощность, а не масса,
     чтобы к осеннему отбору прийти на пике прыжка */
  const holiday = typeof summerModeOf==='function' && summerModeOf(3,week)==='vacation';
  const hyper=(blk%2===0) && !holiday, gain=Math.ceil(blk/2)*12.5;
  let lvl={sq:base.sq+gain, tr:base.tr+gain, oh:base.oh+gain*0.4};
  /* летняя сессия: вес как в первую неделю сессии — форму держим, а не растём (шаг 7, Spiering 2021) */
  let wP=wIn;
  const exam=x=>typeof summerModeOf==='function' && summerModeOf(3,x)==='exam';
  if(exam(week) || (wIn===6 && week>1 && exam(week-1))){   /* и разгрузка сразу после сессии — от того же веса */
    let x=exam(week) ? week : week-1;
    while(x>1 && ((c3w(x-1)-1)%6)+1 < ((c3w(x)-1)%6)+1 && summerModeOf(3,x-1)==='exam') x--;
    wP=((c3w(x)-1)%6)+1;
  }
  if(!hyper) lvl={sq:lvl.sq+2.5*(wP-1), tr:lvl.tr+2.5*(wP-1), oh:lvl.oh+1.25*(wP-1)};
  const dl=(wIn===6), k=hyper?0.78:1, d=dl?0.9:1;
  return {sq:r25(lvl.sq*k*d), tr:r25(lvl.tr*k*d), oh:r25(lvl.oh*k*d),
          sets:dl?2:4, reps:hyper?'8–10':'5',
          kind:dl?'deload':(hyper?'hyper':'build'),
          blockName:hyper?'Блок А · гипертрофия':'Блок Б · реконверсия'};
}

function weekKind(c,w){
  if(c===1 && w>12) return 'session';
  if(c===1) return (w===4||w===8)?'deload':(w===12?'test':'build');
  if(c===2) return C2[Math.min(w,12)].kind;
  return cycle3(w).kind;
}

