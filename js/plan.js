/* Силовая В: верх дома в среду — с 3-й недели цикла 1 и в циклах 2–3, кроме сессии.
   Спина, грудь, дельты и руки — то, что по фото отстаёт и что ногам не мешает:
   помехи от совмещения нагрузок касаются тех мышц, что работают в обеих (Schumann 2022).
   В разгрузку руки выпадают целиком */
function upperDay(cycle, week){
  if(cycle===1 && (week<3 || week>12)) return null;
  const kind=weekKind(cycle,week), dl=kind==='deload', hyper=kind==='hyper';
  const taper=(week===11 && cycle<3);
  const S3=(dl||taper)?2:3, S4=(dl||taper)?2:4, I2=(dl||taper)?1:2, I3=(dl||taper)?2:3;
  const push = cycle===1 ? {id:'e2',name:'Отжимания на брусьях',badge:['Грудь','b-chest'],dose:`${S3} × 8–12`,rest:'в паре с тягой',tech:'pushup',warm:'Один подход 5 повторов в неполную амплитуду. Плечо в брусьях уязвимо, холодным не начинай.'}
    : cycle===2 ? {id:'e2',name:'Брусья с весом',badge:['Грудь','b-chest'],dose:`${S3} × 6–10`,rest:'в паре с тягой',tech:'pushup',warm:'Один подход 5 повторов своим весом.'}
    : {id:'e2',name:'Отжимания с ногами на опоре',badge:['Грудь','b-chest'],dose:`${S3} × 10–15`,rest:'в паре с тягой',tech:'pushup',warm:'Не нужна — плечо размято тягой.'};
  const arms=n=> dl ? 0 : n;
  /* бицепс прямыми подходами (шаг 2): цикл 1 — 2, цикл 2 и блоки силы цикла 3 — 4, в массе 3 + 3 в Силовой Г */
  const curlN = cycle===1 ? 2 : (hyper ? 3 : 4);
  return {id:'d5',title:'Силовая В · верх',when:'Среда · дома',warmup:UPPER_WARM,
    note:'Только верх — ноги отдыхают перед четвергом. Упражнения парами: пока одна мышца отдыхает, работает другая.',ex:[
    {id:'e1',name:'Тяга гантели в наклоне',badge:['Спина','b-back'],dose:`${S4} × ${cycle===1?'10–12':'8–12'} на руку`,rest:`в паре с ${cycle===3?'отжиманиями':'брусьями'}`,tech:'row',warm:'Один подход 10 повторов с половиной веса.'},
    push,
    LATERAL('e3', hyper?4:I3, 'в паре с разведениями'),
    REARDELT('e4', I2, 'в паре с махами'),
    CURL('e5', arms(taper ? 2 : curlN), 'в паре с разгибаниями'),
    OHTRI('e6', arms(hyper?3:2), 'в паре со сгибаниями')]};
}

