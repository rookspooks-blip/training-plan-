/* Разминочные подходы под рабочий вес.
   Чем тяжелее рабочий, тем больше ступеней. Последняя ступень
   не ближе 85% — иначе разминка съест первый рабочий подход.
   bar — вес пустого снаряда: штанга 20, трап-гриф около 25. */
function warmSets(w, bar){
  bar = bar || 20;
  if(!w) return 'Два подхода с пустым грифом по 8 повторов.';
  if(w <= bar + 10) return `${bar} кг × 10, потом сразу рабочий.`;
  const r = x => Math.round(w*x/2.5)*2.5;
  if(w < 70)  return `${bar} × 8 · ${r(0.65)} × 5 · потом рабочий. Отдых между разминочными 1 минута.`;
  if(w < 100) return `${bar} × 8 · ${r(0.5)} × 5 · ${r(0.75)} × 3 · потом рабочий. Отдых 1–2 минуты.`;
  return `${bar} × 8 · ${r(0.45)} × 5 · ${r(0.65)} × 3 · ${r(0.85)} × 2 · потом рабочий. Отдых 2 минуты перед первым рабочим.`;
}

