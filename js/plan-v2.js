/* Где в программе v2 стоит неделя с понедельником tag. null - v1 */
function v2Pos(tag){
  if(typeof settings==='object' && settings.prog && settings.prog.v===1) return null;   /* prog.v=1: принудительно v1 (проверки старых правил) */
  if(!tag || tag<v2Live()) return null;
  const n=Math.floor(daysBetween(v2From(),tag)/7);
  if(n<=6) return {block:1, week:n+1, tag};
  const op=typeof settings==='object' ? settings.opDay : null;
  if(op && /^\d{4}-\d\d-\d\d$/.test(op)){
    const from=addDays(mondayOf(op),-7), rel=daysBetween(mondayOf(op),tag);   /* rel - дней от понедельника недели операции */
    if(tag>=from && rel<8*7) return {block:3, week:Math.floor(daysBetween(from,tag)/7)+1, tag, rel};
  }
  const w=Math.floor(daysBetween(addDays(v2From(),49),tag)/7)+1;
  return {block:2, week:w, tag};
}
