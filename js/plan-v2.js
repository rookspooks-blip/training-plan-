/* ============ Неделя v2: где что стоит (B.5) ============
   Пн А · Вт интервалы · Ср верх · Чт площадка · Пт физра · Сб Б · Вс велосипед спокойно.
   Переносы и правило 48 часов - те же, что в v1 (layout() в training.js) */
function buildWeekV2(P){
  const D=buildV2Days(P), C=cardioFor();
  if(noPE() && P.block===1 && D.d2) D.d2={...D.d2, noWarm:false, warmup:WARM_V2, note:'Физры не было: сначала разминка. '+D.d2.note};
  const S=[D.d1, D.d2, D.d3, D.d4, D['c-tue'], D.d5].filter(Boolean);
  adjustDays(S);
  const L=layout();
  /* Силовая А не в понедельник: до четверга меньше 48 часов - без стартов и прыжков, ноги на подход меньше */
  if(L.d1.dow===3 || L.d1.dow===2){
    if(!isDropped('d1') && D.d1.ex.some(ex=>ex.badge[0]==='Скорость')){
      D.d1={...D.d1, ex:D.d1.ex.filter(ex=>ex.badge[0]!=='Скорость').map(ex=>isLogged(ex)&&ex.badge[0]==='Ноги'?lessSets(ex):ex)};
      L.d1.note+=' До площадки меньше 48 часов: без стартов и прыжков в начале и на подход меньше на ноги.';
    }
  }
  /* интервалы уступают вторник Силовой А и едут в воскресенье */
  const tueDow = (L.d1.dow===2 && !isDropped('d1')) ? 0 : 2;
  const taken=new Set([L.d1.dow, L.d3.dow, tueDow]);
  if(D.d2 && !isDropped('d2')) taken.add(L.d2.dow);
  if(D.d5 && !isDropped('d5')) taken.add(L.d5.dow);
  const out=[];
  out.push({dow:L.d1.dow, id:'d1', type:'gym', day:D.d1, moveNote:L.d1.note});
  out.push({dow:tueDow, id:'c-tue', type:'gym', day:D['c-tue'], moveNote:tueDow===0?'Интервалы переехали на воскресенье: во вторник стоит перенесённая Силовая А.':''});
  if(D.d5) out.push({dow:L.d5.dow, id:'d5', type:'gym', day:D.d5, moveNote:L.d5.note});
  if(D.d2 && !isDropped('d2')) out.push({dow:L.d2.dow, id:'d2', type:'gym', day:D.d2, moveNote:L.d2.note});
  if(D.d4){ out.push({dow:5, id:'d4', type:'gym', day:D.d4, moveNote:''}); taken.add(5); }
  out.push({dow:L.d3.dow, id:'d3', type:'gym', day:D.d3, moveNote:L.d3.note});
  /* воскресенье: велосипед спокойно и мяч, или отдых (nom 114) - занято интервалами, то пропадает */
  if(tueDow!==0 && C.sun){
    const want=0, dow=taken.has(want) ? [3].find(a=>!taken.has(a)) : want;
    if(dow!==undefined){ taken.add(dow); out.push({dow, id:'c-sun', type:'run', ex:'csun', title:'Велосипед', ...C.sun, moveNote:dow!==want?'Сдвинуто: основной день занят силовой.':''}); }
  }
  const RESTS={3:'Полный день без нагрузки перед площадкой.', 5:'Ноги отдыхают перед субботой.'};
  const used=new Set(out.map(e=>e.dow));
  for(let d=0; d<7; d++) if(!used.has(d)) out.push({dow:d, id:'d-rest-'+d, type:'rest', title:'Отдых', why:RESTS[d]||''});
  const tm=e=>hm2min(trainingTime(e)||'23:59')||0;
  out.sort((a,b)=> ((a.dow===0?7:a.dow) - (b.dow===0?7:b.dow)) || (tm(a)-tm(b)));
  return out;
}
